#!/bin/bash
# Windows apps as their own Linux windows ("Coherence"), with WinApps + FreeRDP RemoteApp.
# Run as your desktop user, while win10-gpu is running (VM Switch > Start Windows):
#   bash laptop/host/winapps/setup-winapps.sh <windows-user>
# Asks for sudo once (2 packages) and for the Windows password (stored only in
# ~/.config/winapps/rdp-pass, mode 600, never in the repo).
# The Windows side (RemoteApp allowed, GPU for RDP sessions) is in docs/09-windows-apps.md.
set -euo pipefail
WIN_USER=${1:?usage: setup-winapps.sh <windows-user>}
SRC=$HOME/src/winapps
COMMIT=0b950dc4b823a759015c549a46c35aaaf31c77c0   # tested 2026-11-20
CONF=$HOME/.config/winapps

sudo pacman -S --needed --noconfirm dialog openbsd-netcat >/dev/null   # freerdp is already installed
[ -d "$SRC/.git" ] || git clone -q https://github.com/winapps-org/winapps "$SRC"
git -C "$SRC" fetch -q origin && git -C "$SRC" checkout -q "$COMMIT"

mkdir -p "$CONF"; chmod 700 "$CONF"
if [ ! -s "$CONF/rdp-pass" ]; then
  read -rsp "Windows password for $WIN_USER: " pw; echo
  ( umask 077; printf '%s' "$pw" > "$CONF/rdp-pass" ); unset pw
fi
( umask 077; cat > "$CONF/winapps.conf" <<CONFEOF
# WinApps config for the laptop's win10-gpu VM (generated by laptop/host/winapps/setup-winapps.sh)
RDP_USER="$WIN_USER"
RDP_PASS=""
RDP_ASKPASS="cat $CONF/rdp-pass"
RDP_DOMAIN=""
RDP_IP="192.168.122.13"
RDP_PORT="3389"
VM_NAME="win10-gpu"
# manual: WinApps only connects. It never starts, pauses or stops the VM; the GTX switch stays with
# gpu-mode / VM Switch (a plain 'virsh start' cannot move the GTX, and pausing a GPU VM is unsafe).
WAFLAVOR="manual"
RDP_SCALE="100"
REMOVABLE_MEDIA="/run/media"
RDP_FLAGS="/cert:tofu /sound /microphone +home-drive"
DEBUG="true"
AUTOPAUSE="off"
FREERDP_COMMAND="xfreerdp3"
PORT_TIMEOUT="5"
RDP_TIMEOUT="30"
APP_SCAN_TIMEOUT="60"
BOOT_TIMEOUT="120"
HIDEF="on"
CONFEOF
)
nc -z -w 3 192.168.122.13 3389 || { echo "Windows RDP not reachable: start Windows first (VM Switch)"; exit 1; }
echo "Now the WinApps installer: choose 'Install', then the apps you want (or 'all')."
bash "$SRC/setup.sh" --user
